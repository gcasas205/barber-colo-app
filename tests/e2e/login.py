"""Pruebas de punta a punta del ingreso (spec 002). Uso: python3 -I tests/e2e/login.py (con la app en :3100 y la base local limpia)."""
from playwright.sync_api import sync_playwright
B = "http://localhost:3100"
def ok(c, m): print(("✓ " if c else "✗ ") + m)
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={"width": 360, "height": 800})
    pg = ctx.new_page(); errs = []
    pg.on("console", lambda m: errs.append(m.text) if m.type == "error" else None)
    pg.goto(B + "/ingresar", wait_until="networkidle")
    pg.screenshot(path="/tmp/shots/ingresar-360.png", full_page=True)
    # Contraseña equivocada (RF-1b)
    pg.fill("input[name=email]", "colo@example.com"); pg.fill("input[name=password]", "mala")
    pg.click("button:has-text('Ingresar')"); pg.wait_for_selector("main [role=alert]")
    ok("Revisá el correo y la contraseña" in pg.inner_text("main [role=alert]"), "RF-1b: contraseña equivocada → mensaje sin decir cuál falló")
    # Cliente de prueba 1 (RF-22): tocar la cuenta completa el formulario
    pg.click("button:has-text('Cliente de prueba 1')")
    ok(pg.input_value("input[name=email]") == "cliente1@example.com" and pg.input_value("input[name=password]") != "", "RF-22: la cuenta de prueba completa el formulario")
    pg.click("button[type=submit]:has-text('Ingresar')"); pg.wait_for_url("**/perfil")
    ok(pg.locator("text=Modo de prueba").count() > 0, "RF-22b: franja 'Modo de prueba'")
    pg.wait_for_selector("main h1:has-text('Completá tu perfil')", timeout=8000); ok("Completá tu perfil" in pg.inner_text("main h1"), "RF-9: pide completar el perfil")
    pg.screenshot(path="/tmp/shots/perfil-incompleto.png", full_page=True)
    pg.fill("input[name=name]", "A"); pg.fill("input[name=phone]", "4555-1234")
    pg.click("button:has-text('Guardar y ver horarios')"); pg.wait_for_selector("#error-nombre:has-text('2 y 40')")
    ok("celular, con código de área" in pg.inner_text("#error-celular"), "RF-10, RF-10b: errores junto a cada campo")
    pg.fill("input[name=name]", "Martín"); pg.fill("input[name=phone]", "011 15 3816-3491")
    pg.select_option("select[name=birthDay]", "29"); pg.select_option("select[name=birthMonth]", "2")
    pg.click("button:has-text('Guardar y ver horarios')"); pg.wait_for_url(B + "/")
    pg.wait_for_selector("header >> text=Mi perfil", timeout=8000); ok(pg.locator("header >> text=Mi perfil").count() == 1, "con sesión, la chapa dice 'Mi perfil'")
    pg.goto(B + "/perfil", wait_until="networkidle")
    ok(pg.input_value("input[name=phone]") == "11 3816-3491" and pg.input_value("input[name=name]") == "Martín (demo)", "el perfil guardado vuelve normalizado y con la marca (demo)")
    ok(pg.evaluate("document.cookie").find("sb-") == -1, "RNF-1: la cookie de sesión no se puede leer desde el navegador")
    pg.click("text=Salir >> nth=0"); pg.wait_for_url(B + "/")
    ok(pg.locator("header >> text=Ingresar").count() == 1, "RF-5: salir vuelve a la página pública sin sesión")

    # Invitado (RF-15 a RF-17)
    g = b.new_context(viewport={"width": 390, "height": 844}).new_page()
    g.goto(B + "/ingresar", wait_until="networkidle")
    g.fill("input[name=name]", "Impostor"); g.fill("input[name=phone]", "11 3816 3491")
    g.click("button:has-text('Entrar como invitado')"); g.wait_for_selector("main [role=alert]")
    ok("ya tiene una cuenta" in g.inner_text("main [role=alert]"), "RF-16: un invitado no puede usar el teléfono de una cuenta")
    g.fill("input[name=name]", "Lucas"); g.fill("input[name=phone]", "+598 99 123 456")
    g.click("button:has-text('Entrar como invitado')"); g.wait_for_selector("#error-celular:has-text('Argentina')")
    ok(True, "RF-10: número del exterior con el mensaje para escribirle a Colo")
    g.fill("input[name=phone]", "351 15 512-3456")
    g.click("button:has-text('Entrar como invitado')"); g.wait_for_url("**/perfil")
    g.wait_for_selector("main h1:has-text('Hola')", timeout=8000); ok("Hola, Lucas" in g.inner_text("main h1") and "351 512-3456" in g.inner_text("main"), "RF-15: el invitado entra y ve su cuenta")
    g.screenshot(path="/tmp/shots/invitado.png", full_page=True)

    # Tema: menú compacto (RF-17 de la 001)
    t = b.new_context(viewport={"width": 360, "height": 800}).new_page()
    t.goto(B + "/", wait_until="networkidle")
    t.click("button[aria-label^='Tema:']"); t.click("button[aria-label='Tema oscuro']")
    ok(t.evaluate("document.documentElement.dataset.theme") == "dark", "tema oscuro desde el menú")
    t.screenshot(path="/tmp/shots/publica-360-oscuro.png")
    print("errores de consola:", [e for e in errs if "401" not in e][:3])
    b.close()

# --- Pantalla de Colo (spec 002, T7) ---
with sync_playwright() as p:
    b = p.chromium.launch()
    # Un cliente de prueba no ve nada de Colo (RF-8, caso 13)
    c = b.new_context(viewport={"width": 390, "height": 844}).new_page()
    c.goto(B + "/ingresar", wait_until="networkidle")
    c.click("button:has-text('Cliente de prueba 2')"); c.click("button[type=submit]:has-text('Ingresar')"); c.wait_for_url("**/perfil")
    c.goto(B + "/colo", wait_until="networkidle"); c.wait_for_selector("main h1")
    ok("No tenés acceso" in c.inner_text("main h1") and "Lucas" not in c.inner_text("main"), "RF-8: un cliente que abre /colo no ve datos")
    # Colo (demo)
    pg = b.new_context(viewport={"width": 390, "height": 844}).new_page()
    pg.goto(B + "/ingresar", wait_until="networkidle")
    pg.click("button:has-text('Colo (barbero)')"); pg.click("button[type=submit]:has-text('Ingresar')"); pg.wait_for_url("**/colo")
    pg.wait_for_selector("main h1:has-text('Hola, Colo')")
    text = pg.inner_text("main")
    ok("Lucas" in text and "Invitado" in text and "Cuenta" in text, "RF-19: Colo ve la lista con cuentas e invitados")
    ok(pg.locator("text=Modo de prueba").count() > 0, "RF-22b: franja de prueba también en el panel")
    pg.click("button[aria-label='Poner sobrenombre a Lucas']")
    pg.fill("input[name=nickname]", "el cordobés"); pg.click("button:has-text('Guardar')")
    pg.wait_for_selector("h3:has-text('el cordobés')")
    ok(pg.locator("h3:has-text('el cordobés')").inner_text().startswith("el cordobés"), "RF-20: el sobrenombre aparece primero")
    pg.screenshot(path="/tmp/shots/colo.png", full_page=True)
    # El invitado no ve su sobrenombre (RF-21)
    g2 = b.new_context(viewport={"width": 390, "height": 844}).new_page()
    g2.goto(B + "/ingresar", wait_until="networkidle")
    g2.fill("input[name=name]", "Lucas"); g2.fill("input[name=phone]", "351 15 512-3456")
    g2.click("button:has-text('Entrar como invitado')"); g2.wait_for_url("**/perfil")
    g2.wait_for_selector("main h1:has-text('Hola')")
    ok("cordobés" not in g2.content(), "RF-21: el invitado nunca ve su sobrenombre")
    b.close()
